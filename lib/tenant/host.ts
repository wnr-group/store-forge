import { RESERVED_SLUGS, ROUTES } from "@/config/app";

/**
 * Subdomain routing: <store-slug>.<root domain>. Pure so the proxy and the tests share it.
 * `rootDomain` is NEXT_PUBLIC_ROOT_DOMAIN, including the port locally ("lvh.me:3000") and without
 * it in production ("store-forge.com"). `lvh.me` and every subdomain of it resolve to 127.0.0.1.
 *
 * The result is only a *hint* for which public storefront to render. It grants nothing: the data
 * comes from get_public_storefront(), which exposes public fields of active stores only.
 */
const LABEL = /^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$/;
/** A whole host label, `{store-slug}-{publicId}` (a DNS label is at most 63 characters). */
const HOST_LABEL = /^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/;
/** The tenant's read-only public id, generated by the API (5-8 of a-z0-9). The frontend never makes one. */
const PUBLIC_ID = /^[a-z0-9]{5,8}$/;

/**
 * Request header the proxy sets on a store subdomain so server code knows which store the host names.
 * The proxy ALWAYS deletes any client-supplied copy first, so only the Host header can set it.
 */
export const STORE_HEADER = "x-sf-store";

export const isPublicId = (v: string | null | undefined): v is string => !!v && PUBLIC_ID.test(v);

export const isStoreLabel = (v: string | null | undefined): v is string => !!v && LABEL.test(v) && !v.includes("--");

/**
 * On a store subdomain only these paths are the app (sign-in, that store's dashboard, the sign-in handoff and the open-store redirect); everything
 * else is the public storefront. /admin is deliberately NOT here: the Platform Admin area exists only on
 * the main domain.
 */
export function isSubdomainAppPath(pathname: string): boolean {
  return ["/login", "/dashboard", "/no-workspace", ROUTES.handoff, ROUTES.openStore].some((p) => pathname === p || pathname.startsWith(`${p}/`));
}

export function storeSlugFromHost(host: string | null | undefined, rootDomain: string | null | undefined): string | null {
  if (!host || !rootDomain) return null;
  const h = host.trim().toLowerCase();
  const root = rootDomain.trim().toLowerCase().replace(/^\.+/, "");
  if (!root || !h.endsWith(`.${root}`)) return null;
  const label = h.slice(0, -(root.length + 1));
  if (label.includes(".") || !HOST_LABEL.test(label) || label.includes("--")) return null; // exactly one valid label
  if ((RESERVED_SLUGS as readonly string[]).includes(label)) return null; // www., app., admin., api., ...
  return label;
}

/**
 * Splits a host label into `{store slug}-{public id}`: the public id is the part after the LAST hyphen. This is only a
 * guess about the shape of the label ("acme-store" splits into "acme" + "store"); the caller must confirm it with the API
 * (see resolveStoreHost) before trusting either half.
 */
export function splitStoreLabel(label: string): { slug: string; publicId: string } | null {
  const i = label.lastIndexOf("-");
  if (i < 1) return null;
  const slug = label.slice(0, i);
  const publicId = label.slice(i + 1);
  return isStoreLabel(slug) && isPublicId(publicId) ? { slug, publicId } : null;
}

/**
 * The host label of a store: `{slug}-{publicId}` ("urban-nest-zqkod2"), which is unique per tenant. Without a public id
 * (an API that does not send one yet) it is the bare slug, the older address format.
 */
export const storeHostLabel = (slug: string, publicId?: string | null): string => (isPublicId(publicId) ? `${slug}-${publicId}` : slug);

/** Public URL of a store: http for local roots (lvh.me / localhost), https otherwise. Null when no root domain is configured. */
export function storefrontUrl(slug: string, rootDomain: string | null | undefined, publicId?: string | null): string | null {
  const root = rootDomain?.trim().toLowerCase();
  if (!root) return null;
  const local = /^(localhost|[^.]+\.localhost|lvh\.me|127\.0\.0\.1)(:\d+)?$/.test(root);
  return `${local ? "http" : "https"}://${storeHostLabel(slug, publicId)}.${root}`;
}

/** "urban-nest-zqkod2.lvh.me:3000" - the host part only, for display. Falls back to the bare label when no root domain is set. */
export function storefrontHost(slug: string, rootDomain: string | null | undefined, publicId?: string | null): string {
  const root = rootDomain?.trim().toLowerCase();
  const label = storeHostLabel(slug, publicId);
  return root ? `${label}.${root}` : label;
}

